interface Result { code: number | null; stdout: string; stderr: string }
function run(command: string, args: string[], cwd: string, env: NodeJS.ProcessEnv, input = '', timeoutMs = 20_000): Promise<Result> {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd, env, stdio: ['pipe', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    let bytes = 0;
    const timer = setTimeout(() => fail(new Error(`Process deadline: ${command}`)), timeoutMs);
    function fail(error: Error): void { clearTimeout(timer); child.kill('SIGKILL'); reject(error); }
    function collect(channel: 'stdout' | 'stderr', chunk: Buffer): void {
      bytes += chunk.length;
      if (bytes > byteLimit) return fail(new Error(`Process byte budget: ${command}`));
      if (channel === 'stdout') stdout += chunk.toString('utf8');
      else stderr += chunk.toString('utf8');
    }
    child.stdout.on('data', chunk => collect('stdout', chunk));
    child.stderr.on('data', chunk => collect('stderr', chunk));
    child.stdin.on('error', error => { if ((error as NodeJS.ErrnoException).code !== 'EPIPE') fail(error); });
    child.once('error', fail);
    child.once('close', code => { clearTimeout(timer); resolve({ code, stdout, stderr }); });
    child.stdin.end(input);
  });
}
async function succeed(command: string, args: string[], cwd: string, env: NodeJS.ProcessEnv, timeout = 60_000): Promise<Result> {
  const result = await run(command, args, cwd, env, '', timeout);
  expect(result.code, `${command} ${args.join(' ')}\n${result.stdout}\n${result.stderr}`).toBe(0);
  return result;
}
function outside(candidate: string, root: string): boolean {
  const relative = path.relative(root, candidate);
  return relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative);
}

// Copy genuine installed packages, preserving nested versions; never workspace
// links. Their real installed lock records seed the disposable offline consumer.
async function copyDependency(name: string, from: string, destination: string): Promise<void> {
  const resolver = createRequire(path.join(from, 'package.json'));
  let source: string | undefined;
  for (const parent of resolver.resolve.paths(name) ?? []) {
    const candidate = path.join(parent, name);
    try { if ((await lstat(path.join(candidate, 'package.json'))).isFile()) { source = await realpath(candidate); break; } }
    catch { /* Try the next ordinary Node package location. */ }
  }
  if (!source) throw new Error(`Missing offline installed dependency: ${name}`);
  const sourceRoot = [path.join(checkout, 'packages', 'cli', 'node_modules'), installedModules]
    .find(root => !outside(source!, root));
  if (!sourceRoot) throw new Error(`Dependency outside real installed modules: ${source}`);
  const relative = path.relative(sourceRoot, source);
  if (dependencies.has(relative)) return;
  dependencies.set(relative, source);
  const target = path.join(destination, 'node_modules', relative);
  await mkdir(path.dirname(target), { recursive: true });
  await cp(source, target, { recursive: true, dereference: true });
  const metadata = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
  for (const child of Object.keys({ ...metadata.dependencies, ...metadata.peerDependencies, ...metadata.optionalDependencies })) {
    if (metadata.peerDependenciesMeta?.[child]?.optional || Object.hasOwn(metadata.optionalDependencies ?? {}, child)) {
      const paths = createRequire(path.join(source, 'package.json')).resolve.paths(child) ?? [];
      if (!(await Promise.all(paths.map(p => lstat(path.join(p, child, 'package.json')).then(() => true, () => false)))).some(Boolean)) continue;
    }
    await copyDependency(child, source, destination);
  }
}
async function assertNoLinks(directory: string): Promise<void> {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    expect(entry.isSymbolicLink(), `Consumer package link forbidden: ${file}`).toBe(false);
    if (entry.isDirectory()) await assertNoLinks(file);
  }
}
