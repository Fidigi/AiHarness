import { build } from 'vite';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { validateBase } from './base-path.mjs';
import { filesUnder, validateArtifact } from './artifact.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const dist = path.join(root, 'dist');
const base = validateBase(process.env.DEMO_BASE ?? '/');
await build({ configFile: path.join(root, 'vite.config.ts') });
const assets = (await filesUnder(dist)).map(file => base + file);
const digest = createHash('sha256').update(base);
for (const asset of assets) digest.update(await readFile(path.join(dist, asset.slice(base.length))));
const revision = digest.digest('hex').slice(0, 16);
const scopeId = createHash('sha256').update(base).digest('hex').slice(0, 12);
// All imports/fonts/diagrams are precached, including lazy browser-safe product UI.
await writeFile(path.join(dist, 'sw.js'), `/* Public synthetic demo assets only. Generated by demo/scripts/build.mjs. */
const BASE = ${JSON.stringify(base)};
const ASSETS = ${JSON.stringify(assets)};
const PREFIX = 'aih-demo-${scopeId}-';
const CACHE = PREFIX + '${revision}';
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  await cache.addAll(ASSETS);
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
  await self.clients.claim();
  for (const client of await self.clients.matchAll()) client.postMessage({ type: 'DEMO_OFFLINE_READY' });
})()));
self.addEventListener('message', event => {
  if (event.data?.type === 'DEMO_CACHE_STATUS') event.source?.postMessage({ type: 'DEMO_OFFLINE_READY' });
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || url.search) return;
  const pathname = url.pathname;
  if (!ASSETS.includes(pathname) && pathname !== BASE) return;
  const key = pathname === BASE ? BASE + 'index.html' : pathname;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    return await cache.match(key) || fetch(event.request);
  })());
});
`);
await writeFile(path.join(dist, '.nojekyll'), '');
await writeFile(path.join(dist, 'demo-manifest.json'), JSON.stringify({ version: 1, synthetic: true, base, revision, assets }, null, 2) + '\n');
await validateArtifact(dist, base);
